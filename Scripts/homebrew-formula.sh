#!/bin/sh
# Writes Formula/swx.rb for a release from its SHA256SUMS, so the repository is its own tap:
#
#   brew tap jeslyvarghese/swx https://github.com/jeslyvarghese/swx
#   brew install swx
#
#   Scripts/homebrew-formula.sh <tag> <SHA256SUMS> [output]
# The release workflow runs it after publishing and commits the result.
set -eu

[ $# -ge 2 ] || { echo "usage: $0 <tag> <SHA256SUMS> [output]" >&2; exit 64; }
readonly tag="$1"
readonly sums="$2"
readonly output="${3:-Formula/swx.rb}"
readonly version="${tag#v}"
readonly base="https://github.com/jeslyvarghese/swx/releases/download/$tag"

checksum() {
    sum="$(awk -v name="$1" '$2 == name { print $1 }' "$sums")"
    [ -n "$sum" ] || { echo "$1 is not listed in $sums" >&2; exit 1; }
    echo "$sum"
}

macos="$(checksum swx-macos-universal.tar.gz)"
linux_arm="$(checksum swx-linux-aarch64.tar.gz)"
linux_intel="$(checksum swx-linux-x86_64.tar.gz)"

mkdir -p "$(dirname "$output")"
cat > "$output" <<RUBY
# Generated by Scripts/homebrew-formula.sh for $tag; the release workflow rewrites it.
class Swx < Formula
  desc "Fast package manager that reads and writes SwiftPM's files"
  homepage "https://swx.quadratic.xyz"
  version "$version"
  license "Apache-2.0" => { with: "Swift-exception" }

  on_macos do
    url "$base/swx-macos-universal.tar.gz"
    sha256 "$macos"
  end

  on_linux do
    on_arm do
      url "$base/swx-linux-aarch64.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base/swx-linux-x86_64.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "swx"
    # \`swift x …\` finds swift-x on PATH through SwiftPM's subcommand lookup.
    bin.install_symlink "swx" => "swift-x"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/swx --version").strip
  end
end
RUBY
echo "$output"
